// Regenerates packages/control/src/app-help.generated.ts, the app manual app_help reads, from packages/protocol.
// Usage: node scripts/app-help.mjs [--check]   (run `pnpm build` first; --check exits 1 when the file is stale)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';
import { inputSchemas, sessionTools } from '../packages/protocol/dist/index.js';

const outPath = fileURLToPath(
  new URL('../packages/control/src/app-help.generated.ts', import.meta.url),
);
const sourceDir = fileURLToPath(new URL('../packages/protocol/src/', import.meta.url));
const USER_ONLY = 'the user does this in the app';

// The doc comment right before each quoted command name in the protocol sources.
const docs = new Map();
const DOC = /\/\*\*((?:(?!\*\/)[\s\S])*)\*\/\s*'([a-z][a-z0-9_]*(?:\.[a-z0-9_]+)+)'\s*:/g;
for (const file of fs
  .readdirSync(sourceDir)
  .filter((name) => name.endsWith('.ts'))
  .sort()) {
  const text = fs.readFileSync(path.join(sourceDir, file), 'utf8');
  for (const [, body, name] of text.matchAll(DOC)) {
    if (!Object.hasOwn(inputSchemas, name) || docs.has(name)) continue;
    const doc = body
      .split('\n')
      .map((line) => line.replace(/^\s*\*?\s?/, '').trim())
      .filter(Boolean)
      .join(' ');
    if (doc) docs.set(name, doc);
  }
}

const tools = new Map(Object.entries(sessionTools.lead).map(([tool, type]) => [type, tool]));
// The first sentence of each documented command, as the group's purpose.
const firstSentence = (doc) =>
  doc
    .replace(/^[A-Z][A-Za-z]*(\[\])?[;,:]\s*/, '')
    .split(/(?<=\.)\s/)[0]
    .replace(/\.$/, '');

const names = Object.keys(inputSchemas).sort();
const groups = [...new Set(names.map((name) => name.split('.')[0]))].map((group) => {
  const commands = names
    .filter((name) => name.split('.')[0] === group)
    .map((type) => ({
      type,
      ...(docs.has(type) ? { about: docs.get(type) } : {}),
      tool: tools.get(type) ?? USER_ONLY,
    }));
  const about = [...new Set(commands.filter((c) => c.about).map((c) => firstSentence(c.about)))]
    .join('; ')
    .slice(0, 200);
  return { group, about, commands };
});

const source = [
  '// Generated by scripts/app-help.mjs from packages/protocol; run `pnpm build && node scripts/app-help.mjs` after changing a command.',
  "import type { AppHelpGroup } from './app-help.js';",
  '',
  `export const APP_HELP_USER_ONLY = ${JSON.stringify(USER_ONLY)};`,
  '',
  `export const appHelpGroups: AppHelpGroup[] = ${JSON.stringify(groups)};`,
  '',
].join('\n');
const next = await prettier.format(source, {
  ...(await prettier.resolveConfig(outPath)),
  filepath: outPath,
});
if (process.argv.includes('--check')) {
  const current = fs.existsSync(outPath) ? fs.readFileSync(outPath, 'utf8') : '';
  if (next !== current) {
    console.error(
      'packages/control/src/app-help.generated.ts is stale; run `pnpm build && node scripts/app-help.mjs`',
    );
    process.exitCode = 1;
  }
} else fs.writeFileSync(outPath, next);
